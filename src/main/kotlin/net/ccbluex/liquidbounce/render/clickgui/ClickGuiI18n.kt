package net.ccbluex.liquidbounce.render.clickgui

/**
 * Display-only Chinese localisation for the click GUI.
 *
 * Only text that is drawn goes through here. Logic keys such as `value.name == "Bind"`,
 * `"Hidden"`, `"Enabled"` or module names used for lookups are never translated, so
 * behaviour is identical with [enabled] on or off.
 */
object ClickGuiI18n {

    /** Master switch. When false every call returns the original English text. */
    @JvmStatic
    var enabled: Boolean = true

    private val table: Map<String, String> = parse(RAW)
    private val folded: Map<String, String> = table.mapKeys { it.key.lowercase() }

    /** Translates a complete display string. Unknown text is returned unchanged. */
    fun tr(text: String): String {
        if (!enabled || text.isEmpty()) return text
        return table[text] ?: folded[text.lowercase()] ?: text
    }

    /**
     * Translates a slider unit suffix (e.g. "ms", "blocks"). Exact match only, so single-letter
     * units such as "x" or "s" never leak into the setting-name lookup.
     */
    fun unit(suffix: String): String {
        if (!enabled || suffix.isEmpty()) return suffix
        return table["@unit:" + suffix] ?: suffix
    }

    /**
     * Translates a label that may carry a colour-coded suffix, e.g.
     * `"Name  \u00A77value"` or `"Name \u00A78(unsupported type)"`. Only the leading
     * name and the suffix text are translated; colour codes and spacing are kept.
     */
    fun label(text: String): String {
        if (!enabled) return text
        val cut = text.indexOf('\u00A7')
        if (cut < 0) return tr(text)
        val head = text.substring(0, cut)
        val name = head.trimEnd()
        val spacing = head.substring(name.length)
        val tail = text.substring(cut)
        val translatedTail = if (tail.length >= 2) tail.substring(0, 2) + tr(tail.substring(2)) else tail
        return tr(name) + spacing + translatedTail
    }

    private fun parse(raw: String): Map<String, String> = buildMap {
        raw.lineSequence().forEach { line ->
            val at = line.indexOf("=>")
            if (at > 0) put(line.substring(0, at), line.substring(at + 2))
        }
    }

